"""
test_ZDomain.py — Check if zdomain(a) == a for several example LBLs.
"""
from pypolylib import LBL


# check if: a.included(zdomain(a)) and zdomain(a).included(a)
def test_func(a):
    b = a.zdomain()
    assert a.included(b), "a not included in zdomain(a)"
    assert b.included(a), "zdomain(a) not included in a"
    # equivalent to a == b, with more precise output


# call this function if a test fails:
def fail_func(a):
    print(f"a = {a}")
    print(f"a.zdomain() = {a.zdomain()}")


# list of (name:str, a:lbl)
tests = [
    ("empty",
     LBL("{(i) | 1<0}")),

    ("ZDomain2b",
     LBL("{(i) | 0 <= i, 30j >= i, 29j <= i}")),

    ("ZDomain3",
     LBL("{(i) | 0 <= i <= 10, 3j >= i, 2j <= i}")),

    ("ZDomain4",
     LBL("{(i) | 0 <= i <= 100, 3j >= i, 10j <= 5i-1, 11i <= 20j + 100}")),

    ("ZDomain6",
     LBL("{(2i, 8i+11j) | 24i+44j-k+40>=0, -18i-33j+k-30>=0, -18i-33j+k-30>=0, 24i+44j-l+40>=0, -i+5l>=0, 2i-9l>=0, 2i-9k>=0, -i+5k>=0, i>=51}")),

    ("ZDomain10",
     LBL("{(i, j) | i>=101,  3i-3j+k>=0, -4i+4j-k>=0, -i+10k>=0, i-9k>=0}")),

    # from Pugh91 (the Omega test nightmare)
    ("ZDomain12",
     LBL("{(i, j) | 11i+13j>=27, 11i+13j<=45, 7i-9j+10>=0, -7i+9j+4>=0}")),

    ("ZDomain from ImFlatten",
     LBL("{(i, j) | 3i-10k >= 0, i <= 100, -i+5k >= 0}")),

]


from do_tests import do_tests
do_tests(tests, test_func, fail_func)


